/*
 * Problem 01 - Hello World
 * Session 1: The Road to C
 *
 * The very first C program. We print a few lines of text on the screen.
 */

#include <stdio.h>   /* gives us printf */

int main()
{
    /* printf prints whatever is between the double quotes.
     * "\n" means "move to a new line". */
    printf("Hello, World!\n");
    printf("Welcome to the Wameedh C Workshop.\n");
    printf("Today we write our first C program.\n");

    return 0;   /* 0 means: the program finished successfully */
}
